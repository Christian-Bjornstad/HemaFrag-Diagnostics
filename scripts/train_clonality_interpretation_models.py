def main(argv=None):
    args = _parse_args(argv)
    if args.classifier_kind == "auto" and args.promote_if_passes:
        raise ValueError(
            "--classifier-kind auto is comparison-only; inspect its reports, "
            "then rerun the selected classifier in a fresh output directory "
            "with --promote-if-passes"
        )

    xlsx_path = Path(args.xls)
    if not xlsx_path.exists():
        raise FileNotFoundError(f"--xls {xlsx_path} not found")
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    existing_models = sorted(output_dir.glob("*/metadata.json"))
    if existing_models:
        raise FileExistsError(
            "--output-dir already contains model artifacts; use a fresh "
            f"directory: {output_dir}"
        )
    today = args.date if args.date else datetime.now(timezone.utc).strftime("%Y-%m-%d")
    report_dir = output_dir / "reports" / today
    report_dir.mkdir(parents=True, exist_ok=True)
    print("[train] loading tracking workbook: {}".format(xlsx_path))
    if args.features_csv and args.labels_csv:
        raise ValueError("--features-csv and --labels-csv cannot be used together")
    if args.features_csv:
        if not Path(args.features_csv).is_file():
            raise FileNotFoundError("--features-csv {} not found".format(args.features_csv))
        combined = _assemble_trace_feature_df(
            xlsx_path,
            Path(args.features_csv),
            source_label_col=args.label_column,
        )
    elif args.labels_csv:
        if not Path(args.labels_csv).exists():
            raise FileNotFoundError("--labels-csv {} not found".format(args.labels_csv))
        combined = _assemble_labelled_df_with_labels_csv(
            xlsx_path, Path(args.labels_csv),
            source_label_col=args.label_column,
        )
    else:
        combined = _assemble_labelled_df(
            xlsx_path,
            source_label_col=args.label_column,
        )
    combined = _ensure_columns_renamed(combined)
    print("[train] combined rows: {}".format(len(combined)))

    include_assays = None
    if args.assays:
        include_assays = [s.strip() for s in args.assays.split(",") if s.strip()]

    print("[train] building per-assay datasets (min_samples={})".format(args.min_samples))
    datasets = build_per_assay_datasets(
        combined,
        include_assays=include_assays,
        min_samples_per_assay=args.min_samples,
    )

    if not datasets:
        raise SystemExit(
            "No assays produced a model; raise --min-samples or check the workbook."
        )

    print("[train] found {} qualifying assay(s): {}".format(
        len(datasets), ", ".join(sorted(datasets.keys()))))

    summaries = []
    failed_assays = []
    promotion_failures = []
    # Optional CLI override of per-assay tau — defaults to settings lookup.
    override_tau = getattr(args, "accept_threshold_tau", None)
    for assay_name in sorted(datasets.keys()):
        ds = datasets[assay_name]
        tau = (
            float(override_tau)
            if override_tau is not None
            else _per_assay_threshold_default(assay_name)
        )
        print("[train] assay={}: n_samples={}, tau={}".format(
            assay_name, ds.n_samples, tau))
        candidate_kinds = (
            AUTO_CLASSIFIER_KINDS
            if args.classifier_kind == "auto"
            else (args.classifier_kind,)
        )
        validations = {}
        gates = {}
        model_comparison = []
        for classifier_kind in candidate_kinds:
            print(
                "[train] assay={} validating classifier={}".format(
                    assay_name,
                    classifier_kind,
                )
            )
            try:
                candidate_validation = grouped_oof_validate(
                    ds,
                    classifier_kind=classifier_kind,
                    n_splits=args.validation_folds,
                    random_state=args.random_state,
                    accept_threshold_tau=tau,
                )
                candidate_gate = _candidate_gate(candidate_validation, args)
                validations[classifier_kind] = candidate_validation
                gates[classifier_kind] = candidate_gate
                model_comparison.append(
                    _candidate_record(
                        classifier_kind,
                        candidate_validation,
                        candidate_gate,
                    )
                )
            except Exception as exc:
                model_comparison.append(
                    {
                        "classifier_kind": classifier_kind,
                        "status": "failed",
                        "selected": False,
                        "error": str(exc),
                    }
                )
                print(
                    "[train] assay={} classifier={} FAILED: {}".format(
                        assay_name,
                        classifier_kind,
                        exc,
                    )
                )
        successful_candidates = [
            record
            for record in model_comparison
            if record.get("status") == "complete"
        ]
        if not successful_candidates:
            failed_assays.append(
                {
                    "assay": assay_name,
                    "error": "all classifier candidates failed",
                    "model_comparison": model_comparison,
                }
            )
            continue
        selected_record = max(
            successful_candidates,
            key=_candidate_selection_key,
        )
        selected_record["selected"] = True
        selected_kind = str(selected_record["classifier_kind"])
        validation = validations[selected_kind]
        gate = gates[selected_kind]
        print(
            "[train] assay={} selected classifier={}".format(
                assay_name,
                selected_kind,
            )
        )
        try:
            runtime_eligible = bool(args.promote_if_passes and gate.passed)
            if args.promote_if_passes and not gate.passed:
                promotion_failures.append(assay_name)
            estimator = fit_classifier(
                ds.X,
                ds.y,
                kind=selected_kind,
                random_state=args.random_state,
            )
        except Exception as exc:
            print("[train] assay={} FAILED validation/training: {}".format(assay_name, exc))
            failed_assays.append({"assay": assay_name, "error": str(exc)})
            continue
        metrics = validation.aggregate_metrics
        validation_metadata = {
            "strategy": validation.split_manifest["strategy"],
            "group_column": validation.split_manifest["group_column"],
            "effective_splits": validation.split_manifest["effective_splits"],
            "random_state": validation.split_manifest["random_state"],
            "unique_dit_groups": validation.split_manifest["unique_dit_groups"],
            "every_row_oof_once": validation.split_manifest["every_row_oof_once"],
            "metrics": metrics_as_dict(metrics),
            "promotion_gate": {
                "passed": gate.passed,
                "reasons": gate.reasons,
                "thresholds": gate.thresholds,
            },
            "model_selection": {
                "requested_classifier_kind": args.classifier_kind,
                "selected_classifier_kind": selected_kind,
                "selection_order": [
                    "promotion_gate_passed",
                    "monoklonal_precision",
                    "macro_f1",
                    "monoklonal_f1",
                    "accepted_accuracy",
                    "lower_expected_calibration_error",
                ],
                "candidates": model_comparison,
            },
        }
        paths = serialize_model(
            estimator,
            label_order=list(ANNOTATION_CLASSES_ORDER),
            assay=assay_name,
            accept_threshold_tau=tau,
            classifier_kind=selected_kind,
            rare_class_counts=ds.rare_class_counts,
            trained_at_utc=today,
            output_dir=output_dir,
            feature_columns=list(ds.X.columns),
            schema_version="ml_training_pipeline_v2",
            extra_metadata={
                "deployment_status": (
                    "validated" if runtime_eligible else "candidate"
                ),
                "runtime_eligible": runtime_eligible,
                "training_rows": ds.n_samples,
                "training_dit_groups": int(ds.dit.nunique()),
                "training_data_fingerprint": _training_data_fingerprint(ds),
                "feature_dataset_version": _first_value(
                    ds.rows, "FeatureDatasetVersion"
                ),
                "trace_feature_schema_version": _first_value(
                    ds.rows, "TraceFeatureSchemaVersion"
                ),
                "cohort_feature_schema_version": _first_value(
                    ds.rows, "CohortFeatureSchemaVersion"
                ),
                "validation": validation_metadata,
            },
        )
        report_stem = _safe_assay_name(assay_name)
        report_path = report_dir / "report_{}.md".format(report_stem)
        report_path.write_text(
            _render_per_assay_markdown(
                metrics,
                who_called="train_clonality_interpretation_models",
                validation=validation,
                promotion_gate=gate,
                runtime_eligible=runtime_eligible,
                model_comparison=model_comparison,
            ),
            encoding="utf-8",
        )
        predictions_path = report_dir / "predictions_{}.csv".format(report_stem)
        review_path = report_dir / "review_cases_{}.csv".format(report_stem)
        review_html_path = report_dir / "review_panel_{}.html".format(report_stem)
        drift_path = report_dir / "drift_{}.csv".format(report_stem)
        split_path = report_dir / "splits_{}.json".format(report_stem)
        metrics_path = report_dir / "metrics_{}.json".format(report_stem)
        comparison_path = report_dir / "model_comparison_{}.json".format(
            report_stem
        )
        comparison_csv_path = report_dir / "model_comparison_{}.csv".format(
            report_stem
        )
        validation.predictions.to_csv(predictions_path, index=False)
        validation.review_cases.to_csv(review_path, index=False)
        validation.drift_summary.to_csv(drift_path, index=False)
        review_html_path.write_text(
            render_review_panel_html(validation, promotion_gate=gate),
            encoding="utf-8",
        )
        split_path.write_text(
            json.dumps(validation.split_manifest, indent=2, sort_keys=True),
            encoding="utf-8",
        )
        metrics_path.write_text(
            json.dumps(metrics_as_dict(metrics), indent=2, sort_keys=True),
            encoding="utf-8",
        )
        comparison_path.write_text(
            json.dumps(model_comparison, indent=2, sort_keys=True),
            encoding="utf-8",
        )
        pd.DataFrame(model_comparison).to_csv(comparison_csv_path, index=False)
        summaries.append({
            "assay": assay_name,
            "training_samples": metrics.training_samples,
            "monoklonal_f1": metrics.monoklonal_f1,
            "macro_f1": metrics.macro_f1,
            "monoklonal_precision": float(
                metrics.classification_report.get("monoklonal", {}).get(
                    "precision", 0.0
                )
            ),
            "accepted_accuracy": metrics.accepted_accuracy,
            "accepted_coverage": metrics.accepted_coverage,
            "expected_calibration_error": metrics.expected_calibration_error,
            "requested_classifier_kind": args.classifier_kind,
            "selected_classifier_kind": selected_kind,
            "runtime_eligible": runtime_eligible,
            "deployment_status": "validated" if runtime_eligible else "candidate",
            "promotion_gate_passed": gate.passed,
            "promotion_gate_reasons": gate.reasons,
            "model_path": str(paths["joblib"]),
            "report_path": str(report_path),
            "predictions_path": str(predictions_path),
            "review_cases_path": str(review_path),
            "review_panel_path": str(review_html_path),
            "drift_path": str(drift_path),
            "splits_path": str(split_path),
            "model_comparison_path": str(comparison_path),
        })

    summary_path = output_dir / "reports" / today / "summary.json"
    summary_path.parent.mkdir(parents=True, exist_ok=True)
    summary_path.write_text(
        json.dumps(
            {
                "date": today,
                "summaries": summaries,
                "failed_assays": failed_assays,
                "explicit_promotion_requested": bool(args.promote_if_passes),
                "promotion_failures": promotion_failures,
            },
            indent=2,
        ),
        encoding="utf-8",
    )

    print("[train] wrote models to: {}".format(output_dir))
    print("[train] wrote reports to: {}".format(report_dir))
    if not summaries:
        print("[train] FAILED: no assay model completed")
        return 1
    if promotion_failures:
        print(
            "[train] promotion blocked for: {}".format(
                ", ".join(promotion_failures)
            )
        )
        return 2
    print("[train] DONE")
    return 0


if __name__ == "__main__":
    sys.exit(main())
