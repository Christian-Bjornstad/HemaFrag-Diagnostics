"""scripts/train_clonality_interpretation_models.py

Plan 11 / Phase 3 / T-3.1 CLI driver.

Trains per-assay clonality interpretation models on a labelled
tracking workbook. Persists:
  - One joblib artifact per (assay, classifier_kind)
  - A metadata.json per (assay, classifier_kind)
  - A markdown per-assay report under <output-dir>/<date>/

CLI:
  python -m scripts.train_clonality_interpretation_models \
      --xls /path/to/Clonality_Tracking.xlsx \
      --output-dir /path/to/models \
      --min-samples 200 \
      --classifier-kind random_forest \
      [--assays FR1,TCRG-A]
"""

