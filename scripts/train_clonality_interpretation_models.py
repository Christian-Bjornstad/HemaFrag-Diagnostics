def _assay_key(value):
    return (
        str(value or "")
        .strip()
        .replace(" ", "")
        .replace("-", "")
        .replace("_", "")
        .upper()
    )


def _per_assay_threshold_default(assay):
    """Pull from APP_SETTINGS, fall back to 0.85 if not configured."""
    cfg = APP_SETTINGS.get("analyses", {}).get("clonality", {})
    inter = cfg.get("interpretation", {})
    if not isinstance(inter, dict):
        return 0.85
    tau = inter.get("thresholds", {})
    if not isinstance(tau, dict):
        return 0.85
    assay_key = _assay_key(assay)
    for configured_assay, value in tau.items():
        if configured_assay != "_default" and _assay_key(configured_assay) == assay_key:
            return float(value)
    return float(tau.get("_default", 0.85))


def _assemble_labelled_df(xlsx_path, *, source_label_col=CHEMIST_LABEL_COLUMN):
    """Read a tracking XLSX and return the labelled combined frame.

    Current ``Runs`` workbooks are preferred. Legacy ``Run`` and split
    ``Patient_Runs``/``Control_Runs`` layouts remain supported.

    Requires a separate chemist-reviewed label column. Rule-based
    ``ClonalitySuggestion`` values are retained only as comparison data.
    """
    combined = load_tracking_run_table(
        xlsx_path,
        include_controls=False,
    ).frame
    if combined.empty:
        raise ValueError(f"no combined rows found in {xlsx_path}")
    required = (
        (source_label_col, source_label_col),
        (DIR_COL, "DIT"),
        (ASSAY_COL, "Assay"),
    )
    for col, name in required:
        if col not in combined.columns:
            raise KeyError(
                f"workbook {xlsx_path} has no {name!r} column; "
                "label samples in the Clonality Labeling tab first."
            )
    if source_label_col != LABEL_COL:
        combined[LABEL_COL] = combined[source_label_col]
    return combined


def _render_per_assay_markdown(
    metrics,
    who_called,
    *,
    validation,
    promotion_gate,
    runtime_eligible,
    model_comparison,
):
    """Emit a single markdown file per assay."""
    out_lines = []
    out_lines.append("# Clonality ML - Per-Assay Report: `{}`".format(metrics.assay))
    out_lines.append("")
    out_lines.append("_Generated by `{}`._".format(who_called))
    out_lines.append("")
    out_lines.append("## Summary")
    out_lines.append("")
    out_lines.append("- Assay: `{}`".format(metrics.assay))
    out_lines.append("- Classifier kind: `{}`".format(metrics.classifier_kind))
    out_lines.append("- Grouped out-of-fold samples: **{}**".format(len(validation.predictions)))
    out_lines.append("- Unique DIT groups: **{}**".format(
        validation.split_manifest["unique_dit_groups"]
    ))
    out_lines.append("- Validation folds: **{}**".format(
        validation.split_manifest["effective_splits"]
    ))
    out_lines.append("- Macro F1: **{:.3f}**".format(metrics.macro_f1))
    out_lines.append("- Accuracy: {:.3f}".format(metrics.accuracy))
    out_lines.append("- Balanced accuracy: {:.3f}".format(metrics.balanced_accuracy))
    out_lines.append("- Monoklonal-class F1 (rare-class focus): **{:.3f}**".format(metrics.monoklonal_f1))
    out_lines.append("- Accepted coverage at tau: {:.3f}".format(metrics.accepted_coverage))
    out_lines.append("- Accepted accuracy at tau: **{:.3f}**".format(metrics.accepted_accuracy))
    out_lines.append("- Expected calibration error: {:.3f}".format(
        metrics.expected_calibration_error
    ))
    out_lines.append("- Mean confidence: {:.3f}".format(metrics.mean_confidence))
    out_lines.append("- Per-assay acceptance threshold tau: {}".format(metrics.accept_threshold_tau))
    out_lines.append(
        "- Artifact status: **{}**".format(
            "runtime eligible" if runtime_eligible else "candidate only"
        )
    )
    out_lines.append("")
    out_lines.append("## Model comparison")
    out_lines.append("")
    out_lines.append(
        "| Classifier | Selected | Gate | Macro F1 | Mono precision | "
        "Mono F1 | Accepted accuracy | Coverage | ECE |"
    )
    out_lines.append("|---|---|---|---:|---:|---:|---:|---:|---:|")
    for row in model_comparison:
        if row.get("status") != "complete":
            out_lines.append(
                "| {} | no | failed | - | - | - | - | - | - |".format(
                    row.get("classifier_kind", "")
                )
            )
            continue
        display = {
            **row,
            "selected": "yes" if row["selected"] else "no",
            "gate": "pass" if row["promotion_gate_passed"] else "block",
        }
        out_lines.append(
            "| {classifier_kind} | {selected} | {gate} | {macro_f1:.3f} | "
            "{monoklonal_precision:.3f} | {monoklonal_f1:.3f} | "
            "{accepted_accuracy:.3f} | {accepted_coverage:.3f} | "
            "{expected_calibration_error:.3f} |".format(**display)
        )
    out_lines.append("")
    out_lines.append("## Promotion gate")
    out_lines.append("")
    out_lines.append("- Configured metrics pass: **{}**".format(
        "yes" if promotion_gate.passed else "no"
    ))
    for name, value in promotion_gate.thresholds.items():
        out_lines.append("- `{}`: {}".format(name, value))
    if promotion_gate.reasons:
        for reason in promotion_gate.reasons:
            out_lines.append("- Blocked: {}".format(reason))
    if promotion_gate.passed and not runtime_eligible:
        out_lines.append(
            "- Metrics pass, but explicit `--promote-if-passes` approval was not supplied."
        )
    out_lines.append("")
    out_lines.append("## Fold stability")
    out_lines.append("")
    out_lines.append(
        "| Fold | Train rows | Test rows | Macro F1 | Mono F1 | "
        "Balanced accuracy | Accepted accuracy | Coverage | ECE |"
    )
    out_lines.append("|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    for row in validation.fold_metrics.to_dict(orient="records"):
        out_lines.append(
            "| {Fold} | {TrainRows} | {TestRows} | {MacroF1:.3f} | "
            "{MonoklonalF1:.3f} | {BalancedAccuracy:.3f} | "
            "{AcceptedAccuracy:.3f} | {AcceptedCoverage:.3f} | "
            "{ExpectedCalibrationError:.3f} |".format(**row)
        )
    out_lines.append("")
    out_lines.append("## Rare-class counts")
    out_lines.append("")
    out_lines.append("| Class | Row count |")
    out_lines.append("|---|---|")
    for cls in ANNOTATION_CLASSES_ORDER:
        if cls in metrics.rare_class_counts:
            out_lines.append("| {} | {} |".format(cls, metrics.rare_class_counts[cls]))
    out_lines.append("")

    out_lines.append("## Confusion matrix")
    out_lines.append("")
    out_lines.append("Rows = true, Columns = predicted.")
    out_lines.append("")
    out_lines.append("```")
    cm = metrics.confusion_matrix
    if cm:
        label_keys = [k for k in metrics.classification_report
                      if k not in ("accuracy", "macro avg", "weighted avg") and metrics.classification_report[k].get("support") is not None]
        label_keys.sort(key=lambda k: ANNOTATION_CLASSES_ORDER.index(k) if k in ANNOTATION_CLASSES_ORDER else len(ANNOTATION_CLASSES_ORDER))
        if label_keys:
            out_lines.append(" " * 14 + " ".join("{:>8}".format(c[:6]) for c in label_keys))
            for label in label_keys:
                row_idx = next((i for i, k in enumerate(label_keys) if k == label), None)
                if row_idx is None:
                    continue
                row = cm[row_idx] if row_idx < len(cm) else []
                out_lines.append("{:<14}".format(label[:12]) + " ".join("{:>8d}".format(v) for v in row))
        else:
            for row in cm:
                out_lines.append(" ".join("{:>6d}".format(v) for v in row))
    out_lines.append("```")
    out_lines.append("")

    out_lines.append("## Per-class metrics")
    out_lines.append("")
    for cls in ANNOTATION_CLASSES_ORDER:
        d = metrics.classification_report.get(cls)
        if not d:
            continue
        out_lines.append(
            "- **{}**: precision={:.3f}, recall={:.3f}, f1={:.3f}, support={}".format(
                cls,
                float(d.get("precision", 0.0)),
                float(d.get("recall", 0.0)),
                float(d.get("f1-score", 0.0)),
                int(d.get("support", 0)),
            )
        )
    out_lines.append("")
    out_lines.append("## Decision notes")
    out_lines.append("")
    out_lines.append("- Rule-based interpretation remains the report source of truth.")
    out_lines.append("- ML is a second opinion; disagreement, low confidence, and rare-label predictions route to review.")
    out_lines.append("- Candidate artifacts are ignored by runtime until explicitly promoted after passing configured gates.")
    out_lines.append("")
    return chr(10).join(out_lines)


def _assemble_labelled_df_with_labels_csv(
    xlsx_path,
    labels_csv_path,
    *,
    source_label_col=CHEMIST_LABEL_COLUMN,
):
    """Variant that joins labels from a separate CSV.

    The CSV must have Assay, a chemist label, and either IdentityKey
    (preferred) or DIT. IdentityKey avoids spreading one label across
    multiple same-assay injections.
    """
    combined = load_tracking_run_table(
        xlsx_path,
        include_controls=False,
    ).frame
    if combined.empty:
        raise ValueError("no combined rows found in {}".format(xlsx_path))
    labels = pd.read_csv(labels_csv_path)
    label_aliases = (
        (CHEMIST_LABEL_COLUMN, "label", "y")
        if source_label_col == CHEMIST_LABEL_COLUMN
        else (source_label_col,)
    )
    column_aliases = {
        ASSAY_COL: ("assay",),
        source_label_col: label_aliases,
    }
    for col, aliases in column_aliases.items():
        if col in labels.columns:
            continue
        for alias in aliases:
            if alias in labels.columns:
                labels = labels.rename(columns={alias: col})
                break
        else:
            raise KeyError(
                "labels csv at {} has no {!r} column (or its alias)".format(
                    labels_csv_path, col,
                )
            )
    if "identity_key" in labels.columns and "IdentityKey" not in labels.columns:
        labels = labels.rename(columns={"identity_key": "IdentityKey"})
    if DIR_COL not in labels.columns and "dit" in labels.columns:
        labels = labels.rename(columns={"dit": DIR_COL})

    if "IdentityKey" in labels.columns and "IdentityKey" in combined.columns:
        join_columns = ["IdentityKey", ASSAY_COL]
    elif DIR_COL in labels.columns:
        join_columns = [DIR_COL, ASSAY_COL]
    else:
        raise KeyError(
            "labels csv must contain IdentityKey (preferred) or DIT for a leakage-safe join"
        )
    duplicate_labels = labels.duplicated(subset=join_columns, keep=False)
    if duplicate_labels.any():
        raise ValueError(
            "{} labels CSV row(s) duplicate join key {}".format(
                int(duplicate_labels.sum()), ", ".join(join_columns)
            )
        )
    combined = combined.drop(columns=[source_label_col], errors="ignore")
    merged = combined.merge(
        labels[join_columns + [source_label_col]],
        on=join_columns,
        how="inner",
        validate="many_to_one",
    )
    if merged.empty:
        raise ValueError("overlap between tracking features and labels was empty")
    if source_label_col != LABEL_COL:
        merged[LABEL_COL] = merged[source_label_col]
    return merged


def _assemble_trace_feature_df(
    xlsx_path,
    features_csv_path,
    *,
    source_label_col=CHEMIST_LABEL_COLUMN,
):
    """Join an offline trace artifact to the workbook's latest labels."""
    features = pd.read_csv(features_csv_path)
    required_features = {"IdentityKey", DIR_COL, ASSAY_COL}
    missing_features = sorted(required_features - set(features.columns))
    if missing_features:
        raise KeyError(
            "trace feature CSV is missing: {}".format(", ".join(missing_features))
        )

    tracking = load_tracking_run_table(
        xlsx_path,
        include_controls=False,
    ).frame
    required_tracking = {"IdentityKey", DIR_COL, ASSAY_COL, source_label_col}
    missing_tracking = sorted(required_tracking - set(tracking.columns))
    if missing_tracking:
        raise KeyError(
            "tracking workbook is missing: {}".format(", ".join(missing_tracking))
        )

    features = features.copy()
    tracking = tracking.copy()
    features["_AssayKey"] = features[ASSAY_COL].map(_assay_key)
    tracking["_AssayKey"] = tracking[ASSAY_COL].map(_assay_key)
    join_columns = ["IdentityKey", "_AssayKey"]

    feature_duplicates = features.duplicated(subset=join_columns, keep=False)
    if feature_duplicates.any():
        raise ValueError(
            f"{int(feature_duplicates.sum())} trace feature row(s) duplicate IdentityKey+Assay"
        )
    tracking_duplicates = tracking.duplicated(subset=join_columns, keep=False)
    if tracking_duplicates.any():
        raise ValueError(
            f"{int(tracking_duplicates.sum())} workbook row(s) duplicate IdentityKey+Assay"
        )

    current_labels = tracking[
        join_columns + [DIR_COL, source_label_col]
    ].rename(
        columns={
            DIR_COL: "_CurrentDIT",
            source_label_col: "_CurrentChemistLabel",
        }
    )
    features = features.drop(
        columns=[source_label_col, LABEL_COL],
        errors="ignore",
    )
    merged = features.merge(
        current_labels,
        on=join_columns,
        how="left",
        validate="one_to_one",
        indicator=True,
    )
    unmatched = merged["_merge"].ne("both")
    if unmatched.any():
        raise ValueError(
            f"{int(unmatched.sum())} trace feature row(s) no longer match the tracking workbook"
        )
    merged[DIR_COL] = merged["_CurrentDIT"].fillna("").astype(str)
    merged[LABEL_COL] = merged["_CurrentChemistLabel"]
    return merged.drop(
        columns=["_AssayKey", "_CurrentDIT", "_CurrentChemistLabel", "_merge"]
    )


def _ensure_columns_renamed(combined):
    """Best-effort column-renaming so DIT/Assay/ClonalitySuggestion exist."""
    renames = {}
    for old, new in (
        ("dit", DIR_COL), ("assay", ASSAY_COL), ("y", LABEL_COL),
        ("ClassLabel", LABEL_COL), ("label", LABEL_COL), ("interpretation", LABEL_COL),
    ):
        if old in combined.columns and new not in combined.columns:
            renames[old] = new
    return combined.rename(columns=renames) if renames else combined


def _training_data_fingerprint(dataset) -> str:
    columns = [
        column
        for column in (
            "IdentityKey",
            "FsaContentHash",
            DIR_COL,
            ASSAY_COL,
            LABEL_COL,
        )
        if column in dataset.rows.columns
    ]
    if columns:
        frame = dataset.rows[columns].fillna("").astype(str).copy()
    else:
        frame = pd.DataFrame(
            {
                DIR_COL: dataset.dit.astype(str),
                ASSAY_COL: dataset.assay,
                LABEL_COL: dataset.y.astype(str),
            }
        )
    payload = frame.sort_values(list(frame.columns), kind="stable").to_csv(
        index=False,
        lineterminator="\n",
    )
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def _first_value(frame, column):
    if column not in frame.columns:
        return ""
    values = frame[column].fillna("").astype(str).str.strip()
    values = values.loc[values.ne("")]
    return values.iloc[0] if not values.empty else ""


def _safe_assay_name(value):
    cleaned = "".join(
        character if character.isalnum() or character in {"-", "_"} else "_"
        for character in str(value)
    )
    return cleaned or "unknown"


def _candidate_gate(validation, args):
    return assess_promotion_gate(
        validation,
        min_macro_f1=args.min_macro_f1,
        min_monoklonal_f1=args.min_monoklonal_f1,
        min_monoklonal_precision=args.min_monoklonal_precision,
        min_dit_groups=args.min_dit_groups,
        min_accepted_accuracy=args.min_accepted_accuracy,
        min_accepted_coverage=args.min_accepted_coverage,
        max_expected_calibration_error=args.max_calibration_error,
    )


def _candidate_record(kind, validation, gate):
    metrics = validation.aggregate_metrics
    return {
        "classifier_kind": kind,
        "status": "complete",
        "selected": False,
        "promotion_gate_passed": gate.passed,
        "promotion_gate_reasons": gate.reasons,
        "macro_f1": metrics.macro_f1,
        "monoklonal_f1": metrics.monoklonal_f1,
        "monoklonal_precision": float(
            metrics.classification_report.get("monoklonal", {}).get(
                "precision", 0.0
            )
        ),
        "balanced_accuracy": metrics.balanced_accuracy,
        "accepted_accuracy": metrics.accepted_accuracy,
        "accepted_coverage": metrics.accepted_coverage,
        "expected_calibration_error": metrics.expected_calibration_error,
    }


def _candidate_selection_key(record):
    return (
        bool(record["promotion_gate_passed"]),
        float(record["monoklonal_precision"]),
        float(record["macro_f1"]),
        float(record["monoklonal_f1"]),
        float(record["accepted_accuracy"]),
        -float(record["expected_calibration_error"]),
    )


