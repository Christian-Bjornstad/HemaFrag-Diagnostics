def main(argv=None):
    args = _parse_args(argv)

    xlsx_path = Path(args.xls)
    if not xlsx_path.exists():
        raise FileNotFoundError(f"--xls {xlsx_path} not found")
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    today = args.date if args.date else datetime.now(timezone.utc).strftime("%Y-%m-%d")
    report_dir = output_dir / "reports" / today
    report_dir.mkdir(parents=True, exist_ok=True)
    print("[train] loading tracking workbook: {}".format(xlsx_path))
    if args.labels_csv:
        if not Path(args.labels_csv).exists():
            raise FileNotFoundError("--labels-csv {} not found".format(args.labels_csv))
        combined = _assemble_labelled_df_with_labels_csv(
            xlsx_path, Path(args.labels_csv),
            entry_metadata_path=args.entry_metadata,
        )
    else:
        combined = _assemble_labelled_df(xlsx_path)
    combined = _ensure_columns_renamed(combined)
    print("[train] combined rows: {}".format(len(combined)))

    # Plan 13 / Phase C: overlay chemist annotations on top of rule labels.
    learning_annotations: list[dict] = []
    learning_by_assay: dict[str, int] = {}
    learning_total_seen: int = 0
    if args.annotations_jsonl:
        records, by_assay, total_seen = _load_annotations_jsonl(args.annotations_jsonl)
        learning_annotations = records
        learning_by_assay = by_assay
        learning_total_seen = total_seen
        print(
            "[train] loaded {} annotation rows from {} (skipped {} bad/blank rows)".format(
                len(records), args.annotations_jsonl, total_seen - len(records)
            )
        )
        if records:
            # Match on (DIT, Assay) and overwrite the ClonalitySuggestion column
            # so the chemist's annotation is the authoritative label during
            # the next retrain.
            keys = {
                (str(rec.get("dit") or ""), str(rec.get("assay") or "")): str(
                    rec.get("annotation_class") or ""
                )
                for rec in records
                if rec.get("dit")
            }
            if "DIT" in combined.columns and "Assay" in combined.columns:
                annotated = combined.copy()
                mask = annotated.apply(
                    lambda row: (
                        str(row.get("DIT") or ""),
                        str(row.get("Assay") or ""),
                    )
                    in keys,
                    axis=1,
                )
                annotated.loc[mask, "ClonalitySuggestion"] = annotated.loc[mask].apply(
                    lambda row: keys[
                        (str(row.get("DIT") or ""), str(row.get("Assay") or ""))
                    ],
                    axis=1,
                )
                combined = annotated
                print(
                    "[train] overlaid {} (DIT, Assay) rows with annotation_class".format(
                        int(mask.sum())
                    )
                )
    else:
        print("[train] no --annotations-jsonl provided; rule engine labels only.")

    include_assays = None
    if args.assays:
        include_assays = [s.strip() for s in args.assays.split(",") if s.strip()]

    print("[train] building per-assay datasets (min_samples={})".format(args.min_samples))
    datasets = build_per_assay_datasets(
        combined,
        include_assays=include_assays,
        min_samples_per_assay=args.min_samples,
    )

    if not datasets:
        raise SystemExit(
            "No assays produced a model; raise --min-samples or check the workbook."
        )

    print("[train] found {} qualifying assay(s): {}".format(
        len(datasets), ", ".join(sorted(datasets.keys()))))

    summaries = []
    for assay_name in sorted(datasets.keys()):
        ds = datasets[assay_name]
        tau = _per_assay_threshold_default(assay_name)
        print("[train] assay={}: n_samples={}, tau={}".format(
            assay_name, ds.n_samples, tau))
        try:
            estimator, metrics = _train_one_assay(
                ds,
                classifier_kind=args.classifier_kind,
                test_size=args.test_size,
                random_state=args.random_state,
                accept_threshold_tau=tau,
            )
        except Exception as exc:
            print("[train] assay={} FAILED to fit: {}".format(assay_name, exc))
            continue
        paths = serialize_model(
            estimator,
            label_order=list(ANNOTATION_CLASSES_ORDER),
            assay=assay_name,
            accept_threshold_tau=tau,
            classifier_kind=args.classifier_kind,
            rare_class_counts=ds.rare_class_counts,
            trained_at_utc=today,
            output_dir=output_dir,
        )
        report_path = report_dir / "report_{}.md".format(assay_name)
        report_path.write_text(
            _render_per_assay_markdown(metrics, who_called="train_clonality_interpretation_models"),
            encoding="utf-8",
        )
        summaries.append({
            "assay": assay_name,
            "training_samples": metrics.training_samples,
            "monoklonal_f1": metrics.monoklonal_f1,
            "macro_f1": metrics.macro_f1,
            "model_path": str(paths["joblib"]),
            "report_path": str(report_path),
        })

    summary_path = output_dir / "reports" / today / "summary.json"
    summary_path.parent.mkdir(parents=True, exist_ok=True)
    summary_payload = {
        "date": today,
        "summaries": summaries,
        "learning_annotations_total": len(learning_annotations),
        "learning_annotations_seen_total": learning_total_seen,
        "learning_annotations_by_assay": learning_by_assay,
    }
    summary_path.write_text(json.dumps(summary_payload, indent=2), encoding="utf-8")

    print("[train] wrote models to: {}".format(output_dir))
    print("[train] wrote reports to: {}".format(report_dir))
    print("[train] DONE")
    return 0


if __name__ == "__main__":
    sys.exit(main())


